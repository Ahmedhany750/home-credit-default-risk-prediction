# ===== QUICK TEST (5 min): fast LightGBM to compare ideas =====
def quick_cv(Xq, params_extra=None, seed=42):
    p = dict(objective='binary', metric='auc', learning_rate=0.05, num_leaves=31,
             min_child_samples=80, subsample=0.85, subsample_freq=1, colsample_bytree=0.4,
             reg_alpha=0.5, reg_lambda=2.0, n_estimators=5000, verbose=-1, n_jobs=-1, random_state=seed)
    if params_extra: p.update(params_extra)
    o = np.zeros(len(Xq))
    for tr, va in StratifiedKFold(5, shuffle=True, random_state=seed).split(Xq, y):
        m = lgb.LGBMClassifier(**p).fit(Xq.iloc[tr], y.iloc[tr], eval_set=[(Xq.iloc[va], y.iloc[va])],
                                        callbacks=[lgb.early_stopping(100, verbose=False)])
        o[va] = m.predict_proba(Xq.iloc[va])[:, 1]
    return roc_auc_score(y, o)

base_auc = quick_cv(X)
print(f'Quick baseline AUC: {base_auc:.5f}')

# ===== 4d. New feature ideas — kept only if the quick CV improves =====
def add_new_features(d):
    d = d.copy()
    e1, e2, e3 = d['EXT_SOURCE_1'], d['EXT_SOURCE_2'], d['EXT_SOURCE_3']
    d['EXT_1x2'], d['EXT_1x3'], d['EXT_2x3'] = e1 * e2, e1 * e3, e2 * e3
    d['EXT_HARMONIC'] = 3 / (1 / e1 + 1 / e2 + 1 / e3)
    d['EXT_2_DIV_AGE'] = e2 / d['AGE_YEARS']
    d['N_PAYMENTS'] = d['AMT_CREDIT'] / d['AMT_ANNUITY']
    d['TOTAL_PAYBACK_RATIO'] = (d['AMT_ANNUITY'] * d['N_PAYMENTS'].round()) / d['AMT_CREDIT']
    d['N_PAYMENTS_FRAC'] = d['N_PAYMENTS'] - d['N_PAYMENTS'].round()
    d['INCOME_MINUS_ANNUITY'] = d['AMT_INCOME_TOTAL'] - d['AMT_ANNUITY'] * 12
    d['INCOME_MINUS_ANNUITY_PP'] = d['INCOME_MINUS_ANNUITY'] / d['CNT_FAM_MEMBERS']
    return d.replace([np.inf, -np.inf], np.nan)

def add_freq(dtr, dte, cols=('AMT_CREDIT', 'AMT_ANNUITY', 'AMT_GOODS_PRICE')):
    dtr, dte = dtr.copy(), dte.copy()
    for c in cols:
        cnt = pd.concat([dtr[c], dte[c]]).value_counts()
        dtr[f'FREQ_{c}'] = dtr[c].map(cnt).astype(float)
        dte[f'FREQ_{c}'] = dte[c].map(cnt).astype(float)
    return dtr, dte

X_new, X_test_new = add_new_features(X), add_new_features(X_test)
X_new, X_test_new = add_freq(X_new, X_test_new)
new_auc = quick_cv(X_new)
print(f'Quick baseline: {base_auc:.5f}  |  with new features: {new_auc:.5f}  |  change: {new_auc - base_auc:+.5f}')
if new_auc > base_auc + 0.0003:
    X, X_test = X_new, X_test_new
    features = list(X.columns)
    print('KEPT new features ->', X.shape)
else:
    print('Not kept (no clear gain)')


# ===== 4c. Out-of-fold target features =====
# Both features use TARGET, so they are computed "out-of-fold": a training row never sees its own label.
# Test rows use statistics from the full training set. No external data, fully reproducible.
from sklearn.neighbors import NearestNeighbors

skf_fe = StratifiedKFold(n_splits=5, shuffle=True, random_state=SEED)

# --- (a) Target encoding of categories & category combinations (smoothed mean default rate) ---
def target_encode(tr_col, y_tr, ap_col, smooth=50):
    prior = y_tr.mean()
    stats = pd.DataFrame({'c': tr_col.values, 'y': y_tr.values}).groupby('c')['y'].agg(['sum', 'count'])
    enc = (stats['sum'] + prior * smooth) / (stats['count'] + smooth)
    return ap_col.map(enc).astype(float).fillna(prior).values

def make_key(d, cols):
    key = d[cols[0]].astype(object).fillna('NA').astype(str)
    for c in cols[1:]:
        key = key + '_' + d[c].astype(object).fillna('NA').astype(str)
    return key

te_cols = {
    'ORGANIZATION_TYPE': ['ORGANIZATION_TYPE'],
    'OCCUPATION_TYPE': ['OCCUPATION_TYPE'],
    'ORG_x_OCC': ['ORGANIZATION_TYPE', 'OCCUPATION_TYPE'],
    'INC_x_EDU': ['NAME_INCOME_TYPE', 'NAME_EDUCATION_TYPE'],
    'GENDER_x_FAMILY': ['CODE_GENDER', 'NAME_FAMILY_STATUS'],
    'EDU_x_OCC_x_INC': ['NAME_EDUCATION_TYPE', 'OCCUPATION_TYPE', 'NAME_INCOME_TYPE'],
}
for name, cols in te_cols.items():
    key_tr = make_key(X, cols)
    key_te = make_key(X_test, cols)
    oof_te = np.zeros(len(X))
    for tr_idx, va_idx in skf_fe.split(X, y):
        oof_te[va_idx] = target_encode(key_tr.iloc[tr_idx], y.iloc[tr_idx], key_tr.iloc[va_idx])
    X[f'TE_{name}'] = oof_te
    X_test[f'TE_{name}'] = target_encode(key_tr, y, key_te)
print('Target encodings added:', len(te_cols))

# --- (b) Neighbours' default rate: default rate of the K most similar customers ---
knn_cols = ['EXT_SOURCE_1', 'EXT_SOURCE_2', 'EXT_SOURCE_3', 'CREDIT_TERM']
med = X[knn_cols].median()
A = X[knn_cols].fillna(med)
B = X_test[knn_cols].fillna(med)
mu, sd = A.mean(), A.std()
A, B = ((A - mu) / sd).values, ((B - mu) / sd).values
yv = y.values
for K in [50, 200]:
    oof_knn = np.zeros(len(X))
    for tr_idx, va_idx in skf_fe.split(A, y):
        nn = NearestNeighbors(n_neighbors=K, n_jobs=-1).fit(A[tr_idx])
        idx = nn.kneighbors(A[va_idx], return_distance=False)
        oof_knn[va_idx] = yv[tr_idx][idx].mean(axis=1)
    nn = NearestNeighbors(n_neighbors=K, n_jobs=-1).fit(A)
    X[f'KNN{K}_TARGET_MEAN'] = oof_knn
    X_test[f'KNN{K}_TARGET_MEAN'] = yv[nn.kneighbors(B, return_distance=False)].mean(axis=1)
    print(f'KNN{K} feature added | its own AUC: {roc_auc_score(y, oof_knn):.4f}')


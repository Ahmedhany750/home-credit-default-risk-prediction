"""## 5. Building the model — LightGBM + 5-fold cross-validation
Instead of one 70/30 split, the training data is split into 5 parts; each part is used once for validation.
* The **out-of-fold (OOF) AUC** is a much more reliable estimate of the leaderboard score than a single holdout.
* Each fold's model also predicts the test set; the 5 predictions are averaged.
* `SEEDS`: add more seeds (e.g. `[42, 7, 2026]`) to average more models — slightly better & more stable, but slower.

**Workflow for improving:** change one thing → rerun → keep it only if the CV AUC goes up.
"""

# ===== 5a. LightGBM (Optuna-tuned) =====
import time

params = dict(
    objective='binary', metric='auc',
    learning_rate=0.02, n_estimators=20000, max_depth=-1, subsample_freq=1,
    verbose=-1, n_jobs=-1,
    # tuned with Optuna (cell 4e):
    num_leaves=8, min_child_samples=250, colsample_bytree=0.2177, subsample=0.786,
    reg_alpha=0.0079, reg_lambda=7.166, min_split_gain=0.3635,
)
SEEDS = [42, 7]
N_FOLDS = 10

oof = np.zeros(len(X))
test_pred = np.zeros(len(X_test))
importances = pd.DataFrame(index=features)

for seed in SEEDS:
    skf = StratifiedKFold(n_splits=N_FOLDS, shuffle=True, random_state=seed)
    for fold, (tr_idx, va_idx) in enumerate(skf.split(X, y), 1):
        t0 = time.time()
        model = lgb.LGBMClassifier(**params, random_state=seed)
        model.fit(X.iloc[tr_idx], y.iloc[tr_idx],
                  eval_set=[(X.iloc[va_idx], y.iloc[va_idx])],
                  callbacks=[lgb.early_stopping(200, verbose=False)])
        va_pred = model.predict_proba(X.iloc[va_idx])[:, 1]
        oof[va_idx] += va_pred / len(SEEDS)
        test_pred += model.predict_proba(X_test)[:, 1] / (N_FOLDS * len(SEEDS))
        importances[f's{seed}_f{fold}'] = model.booster_.feature_importance('gain')
        print(f'LGB seed {seed} fold {fold:2d}: AUC = {roc_auc_score(y.iloc[va_idx], va_pred):.5f}  '
              f'(trees: {model.best_iteration_}, {time.time() - t0:.0f}s)')
        del model; gc.collect()

print(f'\n>>> LightGBM Overall CV (OOF) AUC: {roc_auc_score(y, oof):.5f}')
np.save(current_dir / 'lgb_oof.npy', oof)
np.save(current_dir / 'lgb_test.npy', test_pred)
